"""Generate the course presentation from canonical metadata (--write or check)."""
import argparse
from html import escape
import posixpath
import re
from course import load_course, validate_course, lesson_navigation, reading_url, checkpoint_reading_url
from build_catalog import load_registry
from paths import ROOT, SITE
from course_assets import version_assets
from course_sidebar import outline, strip_outline


def link(route, target):
    return escape(posixpath.relpath(target.split('?')[0].split('#')[0], posixpath.dirname(route) or '.')
                  + target[len(target.split('?')[0].split('#')[0]):], quote=True)


def action(route, target, label, primary=False):
    return f'<a class="{"course-primary" if primary else "course-link"}" href="{link(route, target)}">{escape(label)}</a>'


def navigation(route):
    items = ''.join(f'<a href="{link(route, target)}"' + (' aria-current="page"' if route == target else '')
                    + f'>{label}</a>' for target, label in [('index.html', 'Home'), ('roadmap.html', 'Roadmap'), ('library.html', 'Library')])
    return f'''  <nav class="course-nav" aria-label="Course navigation">
    <a class="course-brand" href="{link(route, 'index.html')}"><span class="course-brand-full">RL · Learn, build, transfer</span><span class="course-brand-short">RL course</span></a>
    <button class="course-menu" type="button" aria-controls="course-outline" aria-expanded="false" hidden>Course contents</button>
    <div id="course-menu-links">{items}</div>
  </nav>''' + outline(route)


def page(route, title, body, breadcrumb=''):
    return version_assets(f'''<!doctype html>
<!-- Generated by scripts/build_course.py from assets/course-registry.json. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)} — RL course</title>
<link rel="stylesheet" href="{link(route, 'assets/style.css')}">
<link rel="stylesheet" href="{link(route, 'assets/course.css')}">
<script type="module" src="{link(route, 'assets/course-navigation.js')}"></script></head>
<body class="course-page"><a class="skip-link" href="#main">Skip to content</a>
{navigation(route)}
<main id="main" class="course-content">{breadcrumb}<h1>{escape(title)}</h1>{body}</main>
</body></html>
''')


def lessons_list(course, route, module):
    lessons = {l['id']: l for l in course['lessons']}
    return '<ol class="course-lessons">' + ''.join(
        f'<li data-course-lesson-state="{key}">{action(route, lessons[key]["route"] + "#theory", str(module["number"]) + "." + str(index) + " · " + lessons[key]["title"])}'
        f'<span class="course-meta">About {lessons[key]["minutes"]} minutes · Theory → browser → Python</span></li>'
        for index, key in enumerate(module['lessons'], 1)) + '</ol>'


def resource_list(course, route, ids, lesson=None, module=None):
    resources = {r['id']: r for r in course['resources']}
    result = []
    for key in ids:
        r = resources[key]
        target = checkpoint_reading_url(r, module) if module else reading_url(r, lesson)
        result.append(f'<li data-reading-id="{escape(key)}">{action(route, target, r["title"])}<p>{escape(r["instruction"])}</p></li>')
    return '<ol class="course-readings">' + ''.join(result) + '</ol>'


def outputs(course=None):
    course = course or load_course()
    errors = validate_course(course, load_registry())
    if errors:
        raise ValueError('\n'.join(errors))
    result = {}
    def add(route, title, body, breadcrumb=''):
        result[SITE / route] = page(route, title, body, breadcrumb)
    route = 'index.html'
    overview = ''.join(f'<article class="course-card" data-course-module-state="{m["id"]}"><p class="course-meta">Module {m["number"]} · Project Phase {m["phase"]}</p>'
                       f'<h2>{action(route, m["route"], m["title"])}</h2><p>{escape(m["objective"])}</p>'
                       f'<p>{len(m["lessons"])} lessons</p></article>' for m in course['modules'])
    add(route, 'Learn reinforcement learning, one idea at a time',
        '<p class="course-dek">Read the theory, investigate in your browser, then implement it in local Python. '
        'Finish each module’s project checkpoint and implement that project phase before continuing.</p>'
        f'<section class="course-start" aria-label="Start learning"><p>Begin with Foundations · Build the interaction loop · Read theory</p>'
        f'{action(route, course["lessons"][0]["route"] + "#theory", "Start learning", True)}</section>'
        '<p class="course-meta">25 lessons · 7 modules. Use each lesson guide to choose your next step.</p>'
        f'<p class="course-actions">{action(route, "roadmap.html", "View roadmap")} {action(route, "library.html", "Reference library")}</p>'
        f'<div class="course-grid">{overview}</div>')
    route = 'roadmap.html'
    modules = ''.join(f'<section id="{m["id"]}" data-course-module-state="{m["id"]}"><h2>{action(route, m["route"], str(m["number"]) + ". " + m["title"])}</h2>'
                      f'<p>{escape(m["objective"])} Project Phase {m["phase"]}.</p>{lessons_list(course, route, m)}'
                      f'<p>{action(route, m["projectCheckpoint"]["route"], m["projectCheckpoint"]["preparationLabel"])}</p></section>'
                      for m in course['modules'])
    stages = ''.join(f'<li><strong>Phase {s["phase"]}: {escape(s["title"])}</strong><p>{escape(s["guidance"])}</p>'
                     + (action(route, next(m['route'] for m in course['modules'] if m['id'] == s['module']), 'Open prerequisite module') if s['module'] else '<p>Local project work · no dedicated RL module.</p>') + '</li>' for s in course['projectStages'])
    add(route, 'Course roadmap', '<p>Follow these modules in order. You can browse ahead; preparation is guidance, never a lock.</p>'
        + modules + '<aside><h2>Policy gradients branch</h2><p>PPO builds on its actual lesson prerequisites; self-play is optional preparation.</p>'
        + action(route, 'lessons/p9-reinforce.html#theory', 'View policy gradient preparation') + '</aside>'
        + '<h2 id="project-stages">Project implementation stages</h2><p>Learning readiness and project implementation are separate. '
        'After a checkpoint, implement its project phase locally, then return here for the next stage.</p><ol>' + stages + '</ol>')
    for m in course['modules']:
        route = m['route']; checkpoint = m['projectCheckpoint']
        nav = lesson_navigation(course, m['lessons'][-1]); stage = nav['nextProjectStage']
        body = f'<p class="course-meta">Module {m["number"]} · Project Phase {m["phase"]} · {len(m["lessons"])} lessons</p><p class="course-dek">{escape(m["objective"])}</p>'
        body += action(route, f'lessons/{m["lessons"][0]}.html#theory', 'Start module', True) + lessons_list(course, route, m)
        body += f'<section id="project-checkpoint"><h2>{escape(checkpoint["preparationLabel"])}</h2><p>Finish the module’s lessons, then read these project bridges.</p>'
        body += resource_list(course, route, checkpoint['required'], module=m['id'])
        body += '<h3>Transfer checklist</h3><ul>' + ''.join(f'<li>{escape(c["text"])}</li>' for c in checkpoint['checks']) + '</ul>'
        body += f'<p>When you can explain these contracts, you are ready to implement Phase {m["phase"]} in your local project. '
        body += f'Use the local plan <code>{escape(checkpoint["plan"])}</code>. Course work does not certify production implementation.</p>'
        if stage:
            body += f'<p>After implementation: Phase {stage["phase"]} — {escape(stage["title"])}. {escape(stage["guidance"])}</p>'
        else:
            body += '<p>After this final phase, review the course and reference library as needed.</p>'
        body += action(route, 'roadmap.html#project-stages', 'Return to project roadmap') + '</section>'
        add(route, str(m['number']) + ' · ' + m['title'], body, f'<p class="course-breadcrumb">{action(route, "index.html", "Course")} → Module {m["number"]}</p>')
    for l in course['lessons']:
        route = l['route']; nav = lesson_navigation(course, l['id']); m = nav['module']
        body = f'<p class="course-dek">{escape(l["objective"])}</p>'
        deps = ''.join(f'<li>{action(route, next(x["route"] for x in course["lessons"] if x["id"] == key), next(x["title"] for x in course["lessons"] if x["id"] == key))}</li>' for key in l['prerequisites'])
        body += f'<details><summary>Preparation for this lesson</summary><ul>{deps}</ul><p>{"Review these concepts as needed; you can still browse ahead." if deps else "Python functions, loops, and lists. No prior RL required."}</p></details>'
        body += '<p class="course-meta">1 Read theory → 2 Browser lab → 3 Local Python and reflection</p>'
        body += f'<section id="theory"><h2>1 · Read theory</h2><p>{escape(l["readingGoal"])}</p>'
        body += action(route, nav['readings'][0], 'Read theory: ' + next(r['title'] for r in course['resources'] if r['id'] == l['required'][0]), True)
        body += '<h3>Required now, in order</h3>' + resource_list(course, route, l['required'], l['id']) + '</section>'
        body += '<section id="browser"><h2>2 · Investigate in the browser</h2><p>After the required theory, predict a result and explore the experiment. Hints and solutions are available when requested.</p>' + action(route, nav['browser'], 'Open browser lab') + '</section>'
        body += '<section id="python"><h2>3 · Practice in Python</h2><p>The website guides you; Python runs on your machine. Download the exercise, implement its contracts, run its checks, then record your reflection and local verification in the lab. Optional training does not block the core exercise.</p>' + action(route, nav['python'], 'Practice in Python') + '</section>'
        body += '<section><h2>After this lesson</h2>' + action(route, nav['afterLesson'], m['projectCheckpoint']['preparationLabel'] if nav['moduleEnd'] else 'Next lesson: ' + nav['next']['title']) + '</section>'
        body += '<details><summary>Optional reference and review</summary>' + resource_list(course, route, l['optional']) + '</details>'
        body += '<footer class="course-actions">' + (action(route, nav['previous']['route'], 'Previous lesson: ' + nav['previous']['title']) if nav['previous'] else '') + action(route, 'roadmap.html', 'Back to roadmap') + '</footer>'
        number = str(m['number']) + '.' + str(m['lessons'].index(l['id']) + 1)
        add(route, number + ' · ' + l['title'], body, f'<p class="course-breadcrumb">{action(route, "index.html", "Course")} → {action(route, m["route"], str(m["number"]) + " · " + m["title"])} → {number} · Read theory</p>')
    route = 'library.html'; body = '<p>Browse every preserved reading and experiment by topic. Reference browsing does not set your course resume position.</p>'
    for m in course['modules']:
        body += f'<section><h2>{escape(m["title"])}</h2><ul class="course-library">'
        for r in course['resources']:
            if r['phase'] != m['phase'] or r['kind'] != 'page': continue
            mapped = [l for l in course['lessons'] if any(next(x for x in course['resources'] if x['id'] == key)['route'] == r['route'] for key in l['required'] + l['optional'])]
            body += f'<li><strong>{escape(r["title"])}</strong><span class="course-meta">Reading · {escape(r["category"])}</span>{action(route, r["route"], "Read reference")}'
            body += ''.join(' · ' + action(route, l['route'], 'Open lesson: ' + l['title']) for l in mapped) + '</li>'
        for l in [l for l in course['lessons'] if l['module'] == m['id']]:
            body += f'<li><strong>{escape(l["title"])}</strong><span class="course-meta">Browser lab + Python exercise</span>{action(route, l["lab"], "Open lab reference")} · {action(route, l["route"], "Open lesson")}</li>'
        body += '</ul></section>'
    add(route, 'Reference library', body)
    return result


def integrate_index(route, source):
    """Keep topic contents, replace the index's competing start/sequence instructions."""
    from build_navigation import strip_navigation, integrate_navigation
    source = strip_outline(strip_navigation(source))
    source = re.sub(r'[ \t]*<nav\b.*?</nav>', navigation(route), source, count=1, flags=re.S)
    source = source.replace('class="shell"', 'class="course-reference"')
    source = source.replace('<main>', '<main id="main">')
    if 'href="#main"' not in source:
        source = source.replace('<body>', '<body><a class="skip-link" href="#main">Skip to reference</a>')
    source = re.sub(r'<p class="eyebrow">.*?</p>', '<p class="eyebrow">Topic reference · browse as needed</p>', source, count=1, flags=re.S)
    source = re.sub(r'<div class="note generic"><div class="tag">Learn by experimenting</div>.*?</div>', '', source, flags=re.S)
    source = re.sub(r'<h2>How to use this alongside.*?</h2>\s*<p>.*?</p>', '<h2>Use this as a reference</h2><p>Follow the course roadmap for theory assignments, browser labs, local Python practice, and project checkpoints. Browse the topic contents below whenever you need a reference.</p>', source, flags=re.S)
    source = source.replace('<h2>Reading order</h2>', '<h2>Topic contents</h2>')
    source = re.sub(r'\s*<!-- RL practice links -->.*?<!-- /RL practice links -->\n?', '', source, flags=re.S)
    source = re.sub(r'<p>[^<]*(?:<a[^>]*href="\.\./labs/).*?</p>', '<p>Use the course roadmap for guided lessons; browser experiments and Python packs follow their required theory.</p>', source, flags=re.S)
    source = re.sub(r'<div class="pagenav">.*?</div>', '<div class="pagenav"><a href="../roadmap.html">Course roadmap</a><a href="../library.html">Reference library</a></div>', source, flags=re.S)
    if '<!-- Course reference -->' not in source:
        source = source.replace('</h1>', '</h1><p class="course-start"><!-- Course reference -->' + action(route, 'roadmap.html', 'Course roadmap', True) + ' · ' + action(route, 'library.html', 'Reference library') + '</p>', 1)
    if '../assets/course.css' not in source:
        source = source.replace('</head>', '<link rel="stylesheet" href="../assets/course.css">\n<script type="module" src="../assets/course-navigation.js"></script>\n</head>')
    return integrate_navigation(SITE / route, source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true'); args = parser.parse_args()
    generated = outputs()
    for phase in load_registry()['phases']:
        path = SITE / phase['readingDirectory'] / 'index.html'
        generated[path] = integrate_index(path.relative_to(SITE).as_posix(), path.read_text(encoding='utf-8'))
    stale = []
    for path, source in generated.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source, encoding='utf-8', newline='\n')
        elif not path.is_file() or path.read_text(encoding='utf-8') != source:
            stale.append(path.relative_to(ROOT).as_posix())
    if stale: raise SystemExit('Course pages are stale: ' + ', '.join(stale) + '. Run with --write.')
    print('Home, roadmap, library, 7 modules, 25 lessons and reference indexes ' + ('generated.' if args.write else 'are current.'))


if __name__ == '__main__': main()
