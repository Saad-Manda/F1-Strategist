"""Ship the Phase 8 pit-timing duel to the Pit Wall's Duel mode, and check the JS against it.

    python -m labs.tools.pitwall_duel_game_export export
    python -m labs.tools.pitwall_duel_game_export check

`export` writes site/assets/pitwall/pitgame_data.js: the two 17 x 17 payoff matrices from
labkit.pitgame's cache (blocking on and off), the pass dice of the 20 seeds that made them (numpy's
default_rng(seed), one number per lap, as DuelRace draws them), and the solutions the p8-cap lab
computes from (8, 8): fictitious play after 10,000 rounds, the latest-only cycle, and the plan's
pool rule (70% from the newest 20%, at most 50 entries) after 1,000 rounds.

`check` has pitgame.js recompute both matrices in Node, race by race from the shipped dice, and
compares them with the cache, and the shipped solutions with a fresh run here, to 1e-9.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

import numpy as np

from labs.labkit import games, pitgame

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "site" / "assets" / "pitwall" / "pitgame_data.js"
NODE = Path(__file__).with_name("pitwall_duel_game_parity_node.js")
I8 = pitgame.LAPS.index(8)
N = len(pitgame.LAPS)


def pool_mix(pool, bias):
    n = len(pool)
    if bias is None or n == 1:
        w = np.full(n, 1.0 / n)
    else:
        cut = max(1, int(0.8 * n))
        w = np.where(np.arange(n) >= cut, bias / (n - cut), (1 - bias) / cut)
    mix = np.zeros(N)
    np.add.at(mix, np.asarray(pool), w)
    return mix


def plan_pool(U, rounds=1000, bias=0.7, max_size=50):
    pf, pl, trace = [I8], [I8], []
    for _ in range(rounds):
        pf.append(games.row_best_response(U, pool_mix(pl, bias)))
        pf = pf[-max_size:]
        pl.append(games.col_best_response(U, pool_mix(pf, bias)))
        pl = pl[-max_size:]
        trace.append(games.exploitability(U, pool_mix(pf, bias), pool_mix(pl, bias)))
    return pool_mix(pf, bias), pool_mix(pl, bias), trace


def solve(U):
    f, l, _ = games.fictitious_play(U, 10_000, start=(I8, I8))
    cycle = games.latest_dynamics(U, (I8, I8), 12)
    pf, pl, trace = plan_pool(U)
    return {
        "eq": {"f": f.tolist(), "l": l.tolist(), "value": float(f @ U @ l), "expl": games.exploitability(U, f, l)},
        "cycle": [[pitgame.LAPS[i], pitgame.LAPS[j]] for i, j in cycle],
        "pool": {"f": pf.tolist(), "l": pl.tolist(), "expl": trace[-1], "expl_last200": float(np.mean(trace[-200:]))},
        "U": U.tolist(),
    }


def build():
    dice = [np.random.default_rng(s).random(pitgame.MODEL.horizon).tolist() for s in pitgame.SEEDS]
    return {"laps": pitgame.LAPS, "dice": dice, "on": solve(pitgame.matrix(True)), "off": solve(pitgame.matrix(False))}


def export():
    data = build()
    OUT.write_text(
        "/* Generated by labs/tools/pitwall_duel_game_export.py; do not edit. The Phase 8 pit-timing duel:\n"
        "   both payoff matrices from labkit.pitgame's cache, the 20 seeds' pass dice, and the labs' solutions. */\n"
        "(function (root) { root.PitWall = root.PitWall || {}; root.PitWall.pitgameData = " + json.dumps(data, separators=(",", ":")) + "; })(this);\n"
        "if (typeof module !== \"undefined\" && module.exports) module.exports = this.PitWall.pitgameData;\n",
        encoding="utf-8", newline="\n")
    on = data["on"]
    print(f"wrote {OUT.relative_to(ROOT)}: value {on['eq']['value']:.3f}, exploitability {on['eq']['expl']:.4f}, "
          f"plan's pool {on['pool']['expl']:.3f} (last 200 rounds {on['pool']['expl_last200']:.3f}), cycle {on['cycle'][:3]}")


def check():
    fresh = build()
    text = OUT.read_text(encoding="utf-8")
    shipped = json.loads(text[text.index("pitgameData = ") + len("pitgameData = "):text.index("; })(this);")])
    worst = 0.0
    for tag in ("on", "off"):
        for part in ("U",):
            worst = max(worst, float(np.abs(np.array(shipped[tag][part]) - np.array(fresh[tag][part])).max()))
        for k in ("f", "l"):
            worst = max(worst, float(np.abs(np.array(shipped[tag]["eq"][k]) - np.array(fresh[tag]["eq"][k])).max()))
        if shipped[tag]["cycle"] != fresh[tag]["cycle"]:
            sys.exit(f"DUEL GAME CHECK FAILED: the {tag} cycle differs")
    js = json.loads(subprocess.run(["node", str(NODE)], capture_output=True, text=True, check=True).stdout)
    for tag, interaction in (("on", True), ("off", False)):
        worst = max(worst, float(np.abs(np.array(js[tag]) - pitgame.matrix(interaction)).max()))
        worst = max(worst, abs(js["expl_" + tag] - fresh[tag]["eq"]["expl"]))
    if worst > 1e-9:
        sys.exit(f"DUEL GAME CHECK FAILED: worst difference {worst:.3g}")
    print(f"DUEL GAME CHECK OK (2 matrices, {2 * N * N * len(fresh['dice'])} races in Node, worst difference {worst:.1e})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=("export", "check"))
    args = ap.parse_args()
    export() if args.what == "export" else check()


if __name__ == "__main__":
    main()
